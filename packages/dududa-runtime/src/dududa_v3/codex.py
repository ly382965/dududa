"""Async transport for the locally installed Codex CLI's stdio app server.

Wire fields follow the v2 schema generated by ``codex app-server
generate-json-schema``. No API keys or legacy Dududa runtime are involved.
"""

from __future__ import annotations

import asyncio
import json
import shutil
from collections.abc import Awaitable, Callable
from contextlib import suppress
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

EventCallback = Callable[[dict[str, Any]], Awaitable[None]]


class CodexError(RuntimeError):
    """A local transport, protocol, or Codex turn failure."""


class CodexTimeout(CodexError):
    """The turn exceeded its deadline and was interrupted."""


@dataclass
class CodexResult:
    thread_id: str
    turn_id: str
    text: str
    model: str | None
    tool_calls: list[dict[str, Any]] = field(default_factory=list)
    status: str = "completed"


class CodexClient:
    """One app-server process, with at most one active ``run`` at a time.

    Separate clients can run concurrently. Resuming an unavailable thread fails
    explicitly; this transport never retries or silently starts a new thread.
    """

    def __init__(
        self,
        binary: str = "codex",
        *,
        cwd: Path,
        config_overrides: list[str] | None = None,
        model: str | None = None,
        timeout: float = 180,
    ) -> None:
        self.binary = binary
        self.cwd = Path(cwd).resolve()
        self.config_overrides = list(config_overrides or [])
        self.model = model
        if timeout <= 0:
            raise ValueError("Codex timeout must be positive")
        self.timeout = timeout
        self._process: asyncio.subprocess.Process | None = None
        self._reader: asyncio.Task[None] | None = None
        self._stderr_reader: asyncio.Task[None] | None = None
        self._pending: dict[int, asyncio.Future[Any]] = {}
        self._events: asyncio.Queue[dict[str, Any] | Exception] | None = None
        self._sequence = 0
        self._write_lock = asyncio.Lock()
        self._start_lock = asyncio.Lock()
        self._running = False
        self._closed = False
        self._failure: CodexError | None = None

    async def __aenter__(self) -> CodexClient:  # noqa: PYI034 -- Keep Python 3.10 stdlib-only; typing.Self needs 3.11.
        await self.start()
        return self

    async def __aexit__(self, *exc: object) -> None:
        await self.close()

    async def start(self) -> None:
        async with self._start_lock:
            if self._closed:
                raise CodexError("Codex client is closed")
            if self._failure:
                raise self._failure
            if self._process is not None:
                if self._process.returncode is not None:
                    raise CodexError("Codex app-server has exited")
                return
            executable = shutil.which(self.binary)
            if executable is None:
                raise CodexError(f"Local Codex CLI was not found: {self.binary}")
            args = [executable]
            # Enforce these after caller overrides, then repeat at thread/turn
            # boundaries so a restored thread cannot retain broader permissions.
            for setting in [
                *self.config_overrides,
                'sandbox_mode="read-only"',
                'approval_policy="never"',
            ]:
                args.extend(["-c", setting])
            args.extend(["app-server", "--listen", "stdio://"])
            self._process = await asyncio.create_subprocess_exec(
                *args,
                cwd=self.cwd,
                stdin=asyncio.subprocess.PIPE,
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.PIPE,
                limit=16 * 1024 * 1024,
            )
            self._reader = asyncio.create_task(self._read_stdout())
            self._stderr_reader = asyncio.create_task(self._drain_stderr())
            try:
                await self.request(
                    "initialize",
                    {
                        "clientInfo": {"name": "dududa_v3", "version": "3.0.0"},
                        "capabilities": {"experimentalApi": False},
                    },
                )
                await self._write({"method": "initialized"})
            except BaseException:
                await self.close()
                raise

    async def close(self) -> None:
        self._closed = True
        self._fail(CodexError("Codex app-server connection closed"))
        process = self._process
        if process is not None and process.returncode is None:
            if process.stdin:
                process.stdin.close()
            with suppress(ProcessLookupError):
                process.terminate()
            try:
                await asyncio.wait_for(process.wait(), 3)
            except asyncio.TimeoutError:
                with suppress(ProcessLookupError):
                    process.kill()
                await process.wait()
        for task in (self._reader, self._stderr_reader):
            if task is not None:
                task.cancel()
                with suppress(asyncio.CancelledError):
                    await task

    async def request(self, method: str, params: dict[str, Any]) -> Any:
        if self._failure:
            raise self._failure
        self._sequence += 1
        request_id = self._sequence
        future = asyncio.get_running_loop().create_future()
        self._pending[request_id] = future
        try:
            await self._write({"id": request_id, "method": method, "params": params})
            return await asyncio.wait_for(future, self.timeout)
        finally:
            self._pending.pop(request_id, None)
            if not future.done():
                future.cancel()

    async def cancel(self, thread_id: str, turn_id: str) -> None:
        await self.request("turn/interrupt", {"threadId": thread_id, "turnId": turn_id})

    async def run(
        self,
        text: str,
        thread_id: str | None = None,
        instructions: str = "",
        on_event: EventCallback | None = None,
    ) -> CodexResult:
        if self._running:
            raise CodexError("This Codex client already has an active run")
        self._running = True
        state: dict[str, str] = {}
        # Register before starting the request: notifications may precede its
        # response, including a completed item or an entire very short turn.
        self._events = asyncio.Queue()
        try:
            await self.start()
            return await asyncio.wait_for(
                self._run(text, thread_id, instructions, on_event, state),
                self.timeout,
            )
        except (asyncio.TimeoutError, asyncio.CancelledError) as exc:
            if state.get("thread_id") and state.get("turn_id"):
                try:
                    await asyncio.wait_for(
                        self.cancel(state["thread_id"], state["turn_id"]),
                        min(self.timeout, 5),
                    )
                except (CodexError, asyncio.TimeoutError):
                    await self.close()
            else:
                # If turn/start timed out, it may already have started remotely.
                # Closing prevents an unknown turn from continuing unobserved.
                await self.close()
            if isinstance(exc, asyncio.CancelledError):
                raise
            raise CodexTimeout(f"Codex turn exceeded {self.timeout:g} seconds") from exc
        finally:
            self._events = None
            self._running = False

    async def _run(
        self,
        text: str,
        thread_id: str | None,
        instructions: str,
        on_event: EventCallback | None,
        state: dict[str, str],
    ) -> CodexResult:
        params: dict[str, Any] = {
            "cwd": str(self.cwd),
            "approvalPolicy": "never",
            "sandbox": "read-only",
            "developerInstructions": instructions,
        }
        if self.model:
            params["model"] = self.model
        if thread_id:
            params["threadId"] = thread_id
        response = await self.request("thread/resume" if thread_id else "thread/start", params)
        current_thread = response["thread"]["id"]
        if thread_id and current_thread != thread_id:
            raise CodexError("Codex resumed a different thread than requested")
        state["thread_id"] = current_thread
        model = response.get("model", self.model)
        turn_response = await self.request(
            "turn/start",
            {
                "threadId": current_thread,
                "input": [{"type": "text", "text": text, "text_elements": []}],
                "approvalPolicy": "never",
                "sandboxPolicy": {"type": "readOnly", "networkAccess": False},
            },
        )
        current_turn = turn_response["turn"]["id"]
        state["turn_id"] = current_turn
        messages: dict[str, dict[str, Any]] = {}
        tools: dict[str, dict[str, Any]] = {}

        def remember(item: dict[str, Any]) -> None:
            item_type = item.get("type")
            item_id = item.get("id")
            if not item_id:
                return
            if item_type == "agentMessage":
                messages[item_id] = item
            elif item_type in {
                "mcpToolCall", "commandExecution", "fileChange", "webSearch",
                "dynamicToolCall", "collabAgentToolCall", "imageGeneration",
            }:
                tools[item_id] = item

        assert self._events is not None
        while True:
            event = await self._events.get()
            if isinstance(event, Exception):
                raise event
            method, data = event.get("method"), event.get("params", {})
            event_thread = data.get("threadId") or data.get("thread", {}).get("id")
            event_turn = data.get("turnId") or data.get("turn", {}).get("id")
            if event_thread != current_thread:
                continue
            if event_turn is not None and event_turn != current_turn:
                continue
            if on_event:
                await on_event(event)
            if method == "item/completed":
                remember(data["item"])
            if method != "turn/completed":
                continue
            turn = data["turn"]
            for item in turn.get("items", []):
                remember(item)
            status = turn["status"]
            if status == "failed":
                error = turn.get("error") or {}
                raise CodexError(error.get("message") or "Codex turn failed")
            # Completed notifications may omit items. Keep final messages from
            # item/completed; never promote commentary into a public reply.
            finals = [item for item in messages.values() if item.get("phase") == "final_answer"]
            if not finals:
                finals = [item for item in messages.values() if item.get("phase") is None]
            return CodexResult(
                thread_id=current_thread,
                turn_id=current_turn,
                text="\n\n".join(item.get("text", "") for item in finals),
                model=model,
                tool_calls=list(tools.values()),
                status=status,
            )

    async def _write(self, message: dict[str, Any]) -> None:
        process = self._process
        if process is None or process.stdin is None or process.returncode is not None:
            raise CodexError("Codex app-server is not running")
        async with self._write_lock:
            try:
                process.stdin.write(json.dumps(message, ensure_ascii=False).encode() + b"\n")
                await process.stdin.drain()
            except (BrokenPipeError, ConnectionResetError) as exc:
                raise CodexError("Codex app-server disconnected") from exc

    def _fail(self, error: CodexError) -> None:
        self._failure = self._failure or error
        for future in self._pending.values():
            if not future.done():
                future.set_exception(self._failure)
        if self._events is not None:
            self._events.put_nowait(self._failure)

    async def _read_stdout(self) -> None:
        assert self._process is not None and self._process.stdout is not None
        try:
            while line := await self._process.stdout.readline():
                message = json.loads(line)
                if "method" in message:
                    if "id" in message:
                        # No approval or user-input UI exists in this transport.
                        # An unsupported server request must never grant access.
                        await self._write({
                            "id": message["id"],
                            "error": {"code": -32601, "message": "Unsupported server request"},
                        })
                    elif self._events is not None:
                        self._events.put_nowait(message)
                    continue
                future = self._pending.get(message.get("id"))
                if future is not None and not future.done():
                    if "error" in message:
                        error = message["error"]
                        future.set_exception(CodexError(
                            f"Codex RPC error {error.get('code')}: {error.get('message', 'unknown error')}"
                        ))
                    else:
                        future.set_result(message.get("result"))
            self._fail(CodexError("Codex app-server exited or closed stdout"))
        except asyncio.CancelledError:
            raise
        except (OSError, ValueError, TypeError, AttributeError, CodexError) as exc:
            self._fail(CodexError(f"Codex protocol reader failed: {type(exc).__name__}"))

    async def _drain_stderr(self) -> None:
        assert self._process is not None and self._process.stderr is not None
        # Drain without forwarding local diagnostics into public chat/logs.
        while await self._process.stderr.read(65536):
            pass
